import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<div id="links"><div data-tab="url"></div><div data-tab="html"></div><div data-tab="markdown"></div><div data-tab="thumbnail_url"></div></div>',{url:'https://dayv.cc',runScripts:'outside-only'});
const w=dom.window;w.eval(fs.readFileSync(new URL('../src/public/js/upload-links.js',import.meta.url),'utf8'));
const api=w.LskyUploadLinks,host=w.document.getElementById('links');
const name='双笙（陈元汐） – 我的一个道姑朋友.flac';
const encoded='https://dayv.cc/zGBFCE/'+encodeURIComponent(name);
api.append(host,{url:encoded,html:'&lt;audio controls src="'+encoded+'"&gt;&lt;/audio&gt;',markdown:'[song]('+encoded+')',thumbnail_url:'https://dayv.cc/static/audio.svg'});
const row=host.querySelector('[data-tab="url"] p');
assert.equal(row.textContent,'https://dayv.cc/zGBFCE/'+name);
assert.equal(row.getAttribute('data-link-value'),encoded);
assert.equal(api.copyAll(host,'url'),encoded);
assert.equal(api.copyAll(host,'html'),'<audio controls src="'+encoded+'"></audio>');
assert.equal(api.copyAll(host,'markdown'),'[song]('+encoded+')');
assert(!host.querySelector('audio'));
const r2='https://r2.dayv.cc/1/'+name;
api.append(host,{url:r2});
const rows=host.querySelectorAll('[data-tab="url"] p');
assert.equal(rows[1].textContent,r2);
assert.equal(rows[1].getAttribute('data-link-value'),new URL(r2).href);
assert.equal(api.copyAll(host,'url'),encoded+'\r\n'+new URL(r2).href);
api.append(host,{url:'https://dayv.cc/id/'+encodeURIComponent('<img src=x onerror=alert(1)>')+'.png',html:'&lt;img src=x onerror=alert(1)&gt;',thumbnail_url:'javascript:alert(1)'});
assert.equal(host.querySelectorAll('img').length,4,'only safe preview thumbnails exist');
assert(!host.querySelector('img[onerror]'));assert(!host.querySelector('script'));
assert.equal(api.display('https://a.test/a%2Fb%3Fc%23d%25name.png','url'),'https://a.test/a%2Fb%3Fc%23d%25name.png');
assert.equal(api.display('https://a.test/%E5%ZZ','url'),'https://a.test/%E5%ZZ');
assert.equal(api.display('https://a.test/a%0Ab.png','url'),'https://a.test/a%0Ab.png');
w.eval(fs.readFileSync(new URL('../src/public/js/clipboard/clipboard.min.js',import.meta.url),'utf8'));
const copied=[];w.document.execCommand=function(command){assert.equal(command,'copy');copied.push(w.document.querySelector('textarea').value);return true;};
const single=new w.ClipboardJS('#links [data-link-value]',{text:el=>el.getAttribute('data-link-value')});
row.click();assert.equal(copied.at(-1),encoded,'actual clipboard handler copies encoded value instead of visible text');
const button=w.document.createElement('button');button.id='copy-all';w.document.body.append(button);
const bulk=new w.ClipboardJS('#copy-all',{text:()=>api.copyAll(host,'html')});
button.click();assert.equal(copied.at(-1),api.copyAll(host,'html').replace(/\r\n/g,'\n'),'actual bulk copy preserves HTML syntax');
single.destroy();bulk.destroy();
console.log('PASS readable Chinese URL labels, canonical single/bulk copy, markup compatibility and inert filenames');
dom.window.close();
